/** Дефисы и пробелы в названиях пишут по-разному: «Ростов-на-Дону» и «Ростов на Дону» — один город. */
const lookupKey = (city: string) => cityKey(city)
  .replace(/^(?:г|гор|город|пгт|пос|посёлок|поселок|ст|станица|с)\.?\s+/, '')
  .replace(/[-–—]/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();

const zoneByCity = new Map<string, DeliveryZone>();
for (const zone of deliveryZones) for (const city of zone.cities) zoneByCity.set(lookupKey(city), zone);

/** Разговорные написания крупнейших направлений: покупатель редко печатает официальное имя. */
const cityAliases: Record<string, string> = {
  'спб': 'Санкт-Петербург', 'санкт петербург': 'Санкт-Петербург', 'петербург': 'Санкт-Петербург',
  'питер': 'Санкт-Петербург', 'мск': 'Москва', 'екб': 'Екатеринбург', 'екатеринбург свердловская область': 'Екатеринбург',
  'нижний': 'Нижний Новгород', 'нн': 'Нижний Новгород', 'новосиб': 'Новосибирск',
  'ростов на дону': 'Ростов-на-Дону', 'улан удэ': 'Улан-Удэ', 'йошкар ола': 'Йошкар-Ола',
  'набережные челны': 'Набережные Челны', 'челны': 'Набережные Челны',
};

export const zoneById = (id: string): DeliveryZone | undefined => deliveryZones.find(zone => zone.id === id);

/** Возвращает округ доставки для города или null, когда направление магазином не описано. */
export function findDeliveryZone(city: string): DeliveryZone | null {
  const key = lookupKey(city);
  if (!key) return null;
  const alias = cityAliases[key];
  return zoneByCity.get(alias ? lookupKey(alias) : key) ?? null;
}

/** Города базы знаний для подсказок в поле ввода — по алфавиту, без повторов. */
export const deliveryCities: string[] = [...new Set(deliveryZones.flatMap(zone => zone.cities))]
  .sort((first, second) => first.localeCompare(second, 'ru-RU'));

export const zoneDays = (zone: { min: number; max: number }) =>
  zone.min === zone.max ? `${zone.min}` : `${zone.min}–${zone.max}`;

/** «14–21 дней» покупатель читает как «2–3 недели»: округ Дальнего Востока показывает недели. */
export const zoneTerm = (zone: { min: number; max: number }) =>
  zone.min >= 14 && zone.min % 7 === 0 && zone.max % 7 === 0
    ? `${zone.min / 7}–${zone.max / 7} недели`
    : `${zoneDays(zone)} дн.`;
